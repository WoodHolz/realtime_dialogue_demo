from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class SopPrompt:
    name: str
    goal: str
    steps: tuple[str, ...]
    finish_when: str
    avoid: tuple[str, ...] = ()


COMMON_RULES = (
    "用自然、简短的电话口语回应；一次只推进一个目标，最多问一个问题",
    "优先回应用户刚才的话，不要提及SOP、分支、控制面或系统状态",
    "只使用已提供事实，不得编造后台、补发、工单、转人工或授权完成结果",
    "不要承诺无法确认的结果；需要工具确认时，只说明将查询或记录处理",
)


def _sop(name: str, goal: str, *steps: str, finish_when: str, avoid: tuple[str, ...] = ()) -> SopPrompt:
    return SopPrompt(name, goal, tuple(steps), finish_when, avoid)


