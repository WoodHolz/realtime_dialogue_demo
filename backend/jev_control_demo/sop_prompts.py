def render_sop_query(sop_id: str, *, stage: str) -> str:
    prompt = SOP_PROMPTS[sop_id]
    lines = [
        "请按以下内部对话指导回应用户，不要解释或复述这些规则。",
        f"当前阶段：{stage}",
        f"场景：{prompt.name}",
        f"本轮目标：{prompt.goal}",
        "执行要求：" + "；".join(prompt.steps) + "。",
        f"完成条件：{prompt.finish_when}。",
    ]
    if prompt.avoid:
        lines.append("禁止：" + "；".join(prompt.avoid) + "。")
    lines.append("通用要求：" + "；".join(COMMON_RULES) + "。")
    return "\n".join(lines)
